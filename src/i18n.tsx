const KAMUS: Record<Bahasa, Kamus> = { id, en, zh };
const KUNCI = "kms-bahasa";

function bahasaAwal(): Bahasa {
  try {
    const s = localStorage.getItem(KUNCI);
    if (s === "id" || s === "en" || s === "zh") return s;
  } catch {
    /* tidak tersedia */
  }
  return "id";
}

interface NilaiBahasa {
  bahasa: Bahasa;
  setBahasa: (b: Bahasa) => void;
  t: Kamus;
  locale: string;
}
const Ctx = createContext<NilaiBahasa | null>(null);

export function PenyediaBahasa({ children }: { children: ReactNode }) {
  const [bahasa, setBahasa] = useState<Bahasa>(bahasaAwal);
  useEffect(() => {
    try {
      localStorage.setItem(KUNCI, bahasa);
    } catch {
      /* tidak tersedia */
    }
    document.documentElement.lang = bahasa === "zh" ? "zh-Hant" : bahasa;
  }, [bahasa]);
  const nilai = useMemo(() => ({ bahasa, setBahasa, t: KAMUS[bahasa], locale: BAHASA.find((b) => b.kode === bahasa)!.locale }), [bahasa]);
  return <Ctx.Provider value={nilai}>{children}</Ctx.Provider>;
}

export function useBahasa() {
  const v = useContext(Ctx);
  if (!v) throw new Error("useBahasa harus dipakai di dalam PenyediaBahasa");
  return v;
}
